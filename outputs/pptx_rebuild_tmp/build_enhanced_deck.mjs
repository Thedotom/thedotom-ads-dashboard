function textShapes(slide) {
  return slide.shapes.items.filter((shape) => {
    if (shape.text === undefined || shape.text === null) return false;
    const current = typeof shape.text === "string" ? shape.text : shape.text.toString?.();
    return typeof current === "string" && current.trim().length > 0 && current !== "[object Object]";
  });
}

function rewrite(slide, values) {
  const shapes = textShapes(slide);
  if (shapes.length !== values.length) {
    throw new Error(`Text count mismatch: got ${shapes.length}, expected ${values.length}`);
  }
  shapes.forEach((shape, i) => { shape.text = values[i]; });
}

